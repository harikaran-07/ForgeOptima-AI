"""Furnace status and dashboard aggregation.

Status resolution order:
  1. Live simulation running  -> SIMULATED telemetry (clearly labelled)
  2. Otherwise                -> last recorded heat, labelled as historical
     reference data, not a live sensor reading.
"""
from __future__ import annotations

from datetime import datetime, timedelta, timezone
from typing import Any

from sqlalchemy import select
from sqlalchemy.orm import Session

from ..ml.registry import registry
from ..models import AnomalyRecord, Furnace, HeatRecord, SensorReading
from . import energy
from .simulation import simulator


def get_furnace(db: Session) -> Furnace | None:
    return db.scalar(select(Furnace).order_by(Furnace.id).limit(1))


def latest_heat(db: Session) -> HeatRecord | None:
    return db.scalar(select(HeatRecord).order_by(HeatRecord.heat_started_at.desc()).limit(1))


def _predictions_for(heat: HeatRecord) -> dict[str, float] | None:
    if not registry.is_ready():
        return None
    payload = {
        "metal_grade": heat.metal_grade,
        "charge_weight_kg": heat.charge_weight_kg,
        "initial_temp_c": heat.initial_temp_c,
        "target_temp_c": heat.target_temp_c,
        "power_kw": heat.power_kw,
        "current_a": heat.current_a,
        "voltage_v": heat.voltage_v,
        "ambient_temp_c": heat.ambient_temp_c,
        "melting_time_min": heat.melting_time_min,
    }
    try:
        melt = registry.predict_melting_time(payload)
        kwh = registry.predict_energy(payload)
        return {
            "melting_time_min": melt["predicted_value"],
            "remaining_min": max(melt["predicted_value"] - heat.melting_time_min, 0.0),
            "energy_kwh": kwh["predicted_value"],
        }
    except Exception:
        return None


def status(db: Session) -> dict[str, Any]:
    furnace = get_furnace(db)
    heat = latest_heat(db)
    refs = energy.grade_reference(db)
    live = simulator.snapshot()

    if live["running"] and live["latest"]:
        latest = live["latest"]
        pred = _predictions_for(heat) if heat else None
        return {
            "furnace": furnace,
            "status": "heating",
            "active_heat_id": live["heat_id"],
            "temperature_c": latest["temperature_c"],
            "target_temperature_c": live["target_temp_c"],
            "power_kw": latest["power_kw"],
            "current_a": latest["current_a"],
            "voltage_v": latest["voltage_v"],
            "charge_weight_kg": live["charge_weight_kg"],
            "melt_progress": latest["melt_progress"],
            "energy_kwh": latest["energy_kwh"],
            "predicted_melting_time_min": pred["melting_time_min"] if pred else None,
            "predicted_remaining_min": max(
                (pred["melting_time_min"] if pred else 0) - live["sim_minutes"], 0
            )
            if pred
            else None,
            "predicted_energy_kwh": pred["energy_kwh"] if pred else None,
            "efficiency_score": energy.efficiency_score(
                latest["energy_kwh"] / max(live["charge_weight_kg"], 1.0),
                refs.get(live["metal_grade"], 0.0) or 0.0,
            )
            if refs.get(live["metal_grade"])
            else None,
            "metal_grade": live["metal_grade"],
            "expected_completion": datetime.now(timezone.utc)
            + timedelta(minutes=max((pred["melting_time_min"] if pred else 0) - live["sim_minutes"], 0)),
            "data_mode": "simulated",
            "data_source_note": "SIMULATED DATA — generated by the ForgeOptima live simulator, not plant sensors.",
            "last_updated": datetime.now(timezone.utc),
        }

    if heat is None:
        return {
            "furnace": furnace,
            "status": "no_data",
            "active_heat_id": None,
            "temperature_c": 0.0,
            "target_temperature_c": 0.0,
            "power_kw": 0.0,
            "current_a": 0.0,
            "voltage_v": 0.0,
            "charge_weight_kg": 0.0,
            "melt_progress": 0.0,
            "energy_kwh": 0.0,
            "predicted_melting_time_min": None,
            "predicted_remaining_min": None,
            "predicted_energy_kwh": None,
            "efficiency_score": None,
            "metal_grade": None,
            "expected_completion": None,
            "data_mode": "offline",
            "data_source_note": "No heat records. Upload a CSV, add a manual heat, or start the simulator.",
            "last_updated": datetime.now(timezone.utc),
        }

    readings = list(
        db.scalars(
            select(SensorReading)
            .where(SensorReading.heat_record_id == heat.id)
            .order_by(SensorReading.elapsed_min)
        )
    )
    last = readings[-1] if readings else None
    pred = _predictions_for(heat)
    epk = energy.energy_per_kg(heat)

    return {
        "furnace": furnace,
        "status": "holding" if heat.heat_status == "completed" else heat.heat_status,
        "active_heat_id": heat.heat_id,
        "temperature_c": last.temperature_c if last else heat.target_temp_c,
        "target_temperature_c": heat.target_temp_c,
        "power_kw": last.power_kw if last else heat.power_kw,
        "current_a": last.current_a if last else heat.current_a,
        "voltage_v": last.voltage_v if last else heat.voltage_v,
        "charge_weight_kg": heat.charge_weight_kg,
        "melt_progress": 100.0 if heat.heat_status == "completed" else (last.melt_progress if last else 0.0),
        "energy_kwh": last.energy_kwh if last else heat.energy_kwh,
        "predicted_melting_time_min": pred["melting_time_min"] if pred else None,
        "predicted_remaining_min": pred["remaining_min"] if pred else None,
        "predicted_energy_kwh": pred["energy_kwh"] if pred else None,
        "efficiency_score": energy.efficiency_score(epk, refs.get(heat.metal_grade, epk)),
        "metal_grade": heat.metal_grade,
        "expected_completion": heat.heat_completed_at,
        "data_mode": "historical",
        "data_source_note": (
            f"Historical reference from heat {heat.heat_id} ({heat.heat_started_at:%d %b %Y %H:%M} UTC). "
            "Start the simulator for live-like monitoring."
        ),
        "last_updated": datetime.now(timezone.utc),
    }


def _series(readings: list[SensorReading], key: str, every: int = 3) -> list[dict[str, Any]]:
    return [
        {
            "minute": round(r.elapsed_min, 1),
            key: round(getattr(r, key), 2),
        }
        for r in readings[::every]
    ]


def dashboard(db: Session) -> dict[str, Any]:
    st = status(db)
    heat = latest_heat(db)
    refs = energy.grade_reference(db)
    grades = energy.grade_analytics(db)

    readings: list[SensorReading] = []
    if heat is not None:
        readings = list(
            db.scalars(
                select(SensorReading)
                .where(SensorReading.heat_record_id == heat.id)
                .order_by(SensorReading.elapsed_min)
            )
        )

    temperature_series = [
        {
            "minute": round(r.elapsed_min, 1),
            "temperature_c": round(r.temperature_c, 1),
            "target_c": heat.target_temp_c if heat else 0,
        }
        for r in readings[::3]
    ]
    power_series = [
        {
            "minute": round(r.elapsed_min, 1),
            "power_kw": round(r.power_kw, 1),
            "current_a": round(r.current_a, 1),
        }
        for r in readings[::3]
    ]

    recent = list(
        db.scalars(select(HeatRecord).order_by(HeatRecord.heat_started_at.desc()).limit(12))
    )
    energy_by_heat = [
        {
            "heat_id": h.heat_id,
            "energy_kwh": round(h.energy_kwh, 1),
            "energy_per_kg": round(energy.energy_per_kg(h), 4),
            "grade": h.metal_grade,
        }
        for h in reversed(recent)
    ]

    # predicted vs actual melting time for the most recent heats (real inference)
    melting_performance = []
    for h in reversed(recent[:8]):
        actual = h.melting_time_min
        predicted = None
        if registry.is_ready():
            try:
                predicted = registry.predict_melting_time(
                    {
                        "metal_grade": h.metal_grade,
                        "charge_weight_kg": h.charge_weight_kg,
                        "initial_temp_c": h.initial_temp_c,
                        "target_temp_c": h.target_temp_c,
                        "power_kw": h.power_kw,
                        "ambient_temp_c": h.ambient_temp_c,
                        "elapsed_min": 0,
                    }
                )["predicted_value"]
            except Exception:
                predicted = None
        melting_performance.append(
            {
                "heat_id": h.heat_id,
                "actual_min": round(actual, 1),
                "predicted_min": round(predicted, 1) if predicted else None,
            }
        )

    alerts = list(
        db.scalars(
            select(AnomalyRecord)
            .order_by(AnomalyRecord.detected_at.desc())
            .limit(6)
        )
    )

    kpis = {
        "active_furnace": st["furnace"].name if st["furnace"] else "No furnace configured",
        "furnace_status": st["status"],
        "current_temperature_c": st["temperature_c"],
        "current_power_kw": st["power_kw"],
        "current_current_a": st["current_a"],
        "voltage_v": st["voltage_v"],
        "charge_weight_kg": st["charge_weight_kg"],
        "predicted_melting_time_min": st["predicted_melting_time_min"],
        "predicted_energy_kwh": st["predicted_energy_kwh"],
        "efficiency_score": st["efficiency_score"],
        "active_heat_id": st["active_heat_id"],
        "metal_grade": st["metal_grade"],
        "data_mode": st["data_mode"],
        "data_source_note": st["data_source_note"],
        "prediction_models_ready": registry.is_ready(),
    }

    progress = {
        "heat_id": st["active_heat_id"],
        "melt_progress": st["melt_progress"],
        "temperature_c": st["temperature_c"],
        "target_temp_c": st["target_temperature_c"],
        "predicted_remaining_min": st["predicted_remaining_min"],
        "expected_completion": st["expected_completion"],
        "energy_kwh": st["energy_kwh"],
    }

    return {
        "kpis": kpis,
        "alerts": alerts,
        "recent_heats": recent[:8],
        "temperature_series": temperature_series,
        "power_series": power_series,
        "energy_by_heat": energy_by_heat,
        "melting_performance": melting_performance,
        "grade_performance": grades,
        "progress": progress,
        "benchmarks": {g: round(v, 4) for g, v in refs.items()},
    }
